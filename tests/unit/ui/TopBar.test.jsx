// @vitest-environment jsdom
import { describe, it, expect, vi, afterEach } from 'vitest'
import { screen, fireEvent, within, act } from '@testing-library/react'
import { renderUi } from './helpers.jsx'
import { TopBar } from '../../../src/renderer/components/TopBar.jsx'
import { EMPTY_STATS } from '../../../src/shared/stats.js'

const props = (over = {}) => ({ page: 'home', onNavigate: vi.fn(), health: { light: 'green', reason: 'ok' }, onSemaphoreClick: vi.fn(), profileName: 'Nikola Lelekovic', stats: EMPTY_STATS, ...over })
const PAGES = ['Početna', 'Otkrij', 'Watchlist', 'Raspored', 'Preuzeto']

afterEach(() => { delete window.matchMedia })

describe('TopBar', () => {
  it('shows the five pages with aria-current', () => {
    renderUi(<TopBar {...props({ page: 'watchlist' })} />)
    const nav = screen.getByRole('navigation')
    const names = within(nav).getAllByRole('button').map((b) => b.textContent)
    expect(names).toEqual(PAGES)
    expect(within(nav).getByRole('button', { name: 'Watchlist' })).toHaveAttribute('aria-current', 'page')
    expect(within(nav).getByRole('button', { name: 'Početna' })).not.toHaveAttribute('aria-current')
    expect(within(nav).queryByRole('button', { name: 'Profil' })).toBeNull()
    expect(within(nav).queryByRole('button', { name: 'Podešavanja' })).toBeNull()
  })
  it('navigates from the page buttons', () => {
    const p = props()
    renderUi(<TopBar {...p} />)
    fireEvent.click(screen.getByRole('button', { name: 'Otkrij' }))
    expect(p.onNavigate).toHaveBeenCalledWith('discover')
    fireEvent.click(screen.getByRole('button', { name: 'Raspored' }))
    expect(p.onNavigate).toHaveBeenLastCalledWith('schedule')
  })
  it('right side keeps every sidebar function', () => {
    const p = props({ onOpenPalette: vi.fn() })
    renderUi(<TopBar {...p} />)
    const search = screen.getByRole('button', { name: 'Brza pretraga' })
    expect(search).toHaveAttribute('aria-keyshortcuts', 'Control+K')
    fireEvent.click(search)
    expect(p.onOpenPalette).toHaveBeenCalled()
    const sem = screen.getByRole('button', { name: 'Sve radi' })
    expect(sem).toHaveAttribute('title', 'Sve radi')
    expect(sem).toHaveAttribute('data-light', 'green')
    fireEvent.click(sem)
    expect(p.onSemaphoreClick).toHaveBeenCalled()
    expect(screen.getByRole('button', { name: /Obaveštenja/ })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Podešavanja' }))
    expect(p.onNavigate).toHaveBeenCalledWith('settings')
  })
  it('shows the semaphore as a dot without a text label', () => {
    renderUi(<TopBar {...props()} />)
    expect(screen.getByRole('button', { name: 'Sve radi' }).querySelector('.semaphore__label')).toBeNull()
  })
  describe('avatar menu', () => {
    it('opens with level, Profil, fullscreen and the version', () => {
      const p = props({ version: '0.18.0', onToggleFullscreen: vi.fn(), stats: { ...EMPTY_STATS, level: 11, title: 'veteran' } })
      renderUi(<TopBar {...p} />)
      const avatar = screen.getByRole('button', { name: 'Nalog' })
      expect(avatar).toHaveAttribute('aria-haspopup', 'menu')
      expect(avatar).toHaveAttribute('aria-expanded', 'false')
      expect(avatar).toHaveTextContent('NL')
      fireEvent.click(avatar)
      expect(avatar).toHaveAttribute('aria-expanded', 'true')
      const menu = screen.getByRole('menu')
      // name, level and XP sit in the popup around the menu, not inside role=menu
      expect(screen.getByText('Nikola Lelekovic')).toBeInTheDocument()
      expect(screen.getByText('LV 11')).toBeInTheDocument()
      expect(screen.getByRole('progressbar')).toBeInTheDocument()
      expect(menu).not.toContainElement(screen.getByText('LV 11'))
      expect(menu).not.toContainElement(screen.getByText('v0.18.0 · by Leqora'))
      expect(menu.children.length).toBe(menu.querySelectorAll('[role="menuitem"]').length)
      fireEvent.click(within(menu).getByRole('menuitem', { name: 'Ceo ekran (F11)' }))
      expect(p.onToggleFullscreen).toHaveBeenCalled()
      expect(screen.queryByRole('menu')).toBeNull()
      expect(document.activeElement).toBe(avatar)
      fireEvent.click(avatar)
      fireEvent.click(screen.getByRole('menuitem', { name: 'Profil' }))
      expect(p.onNavigate).toHaveBeenCalledWith('profile', { focusMain: true })
      expect(screen.queryByRole('menu')).toBeNull()
    })
    it('signs the app without a version', () => {
      renderUi(<TopBar {...props({ version: '' })} />)
      fireEvent.click(screen.getByRole('button', { name: 'Nalog' }))
      expect(screen.getByText('by Leqora')).toBeInTheDocument()
      expect(screen.queryByText(/^v\d/)).toBeNull()
    })
    it('offers leaving fullscreen while in fullscreen', () => {
      renderUi(<TopBar {...props({ fullscreen: true })} />)
      fireEvent.click(screen.getByRole('button', { name: 'Nalog' }))
      expect(screen.getByRole('menuitem', { name: 'Izađi iz celog ekrana (Esc)' })).toBeInTheDocument()
    })
    it('Esc closes it and focuses the avatar; arrows move through the items', () => {
      renderUi(<TopBar {...props()} />)
      const avatar = screen.getByRole('button', { name: 'Nalog' })
      avatar.focus()
      fireEvent.keyDown(avatar, { key: 'ArrowDown' })
      const items = screen.getAllByRole('menuitem')
      expect(items.length).toBe(2)
      expect(document.activeElement).toBe(items[0])
      fireEvent.keyDown(items[0], { key: 'ArrowDown' })
      expect(document.activeElement).toBe(items[1])
      fireEvent.keyDown(items[1], { key: 'ArrowDown' })
      expect(document.activeElement).toBe(items[0])
      fireEvent.keyDown(items[0], { key: 'ArrowUp' })
      expect(document.activeElement).toBe(items[1])
      fireEvent.keyDown(items[1], { key: 'Home' })
      expect(document.activeElement).toBe(items[0])
      fireEvent.keyDown(items[0], { key: 'End' })
      expect(document.activeElement).toBe(items[1])
      fireEvent.keyDown(items[1], { key: 'Escape' })
      expect(screen.queryByRole('menu')).toBeNull()
      expect(document.activeElement).toBe(avatar)
    })
    it('Tab and a click outside close it', () => {
      renderUi(<TopBar {...props()} />)
      const avatar = screen.getByRole('button', { name: 'Nalog' })
      fireEvent.click(avatar)
      fireEvent.keyDown(screen.getAllByRole('menuitem')[0], { key: 'Tab' })
      expect(screen.queryByRole('menu')).toBeNull()
      fireEvent.click(avatar)
      expect(screen.getByRole('menu')).toBeInTheDocument()
      fireEvent.mouseDown(document.body)
      expect(screen.queryByRole('menu')).toBeNull()
    })
  })
  it('closes an open menu when the player opens', () => {
    const { rerender } = renderUi(<TopBar {...props()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Nalog' }))
    expect(screen.getByRole('menu')).toBeInTheDocument()
    rerender(<TopBar {...props({ playerOpen: true })} />)
    expect(screen.queryByRole('menu')).toBeNull()
  })
  describe('crossing the 1000 px breakpoint', () => {
    const mockMedia = (initial) => {
      let listener = null
      window.matchMedia = vi.fn((query) => ({ matches: initial, media: query, addEventListener: (_e, fn) => { listener = fn }, removeEventListener: () => { listener = null } }))
      return (matches) => act(() => { listener?.({ matches }) })
    }
    it('moves focus from a nav link to the Menu trigger when the window gets narrow', () => {
      const flip = mockMedia(false)
      renderUi(<TopBar {...props({ page: 'discover' })} />)
      act(() => screen.getByRole('button', { name: 'Watchlist' }).focus())
      flip(true)
      expect(screen.getByRole('button', { name: 'Meni' })).toHaveFocus()
    })
    it('moves focus from the Menu trigger to the active page link when the window gets wide', () => {
      const flip = mockMedia(true)
      renderUi(<TopBar {...props({ page: 'discover' })} />)
      act(() => screen.getByRole('button', { name: 'Meni' }).focus())
      flip(false)
      expect(screen.getByRole('button', { name: 'Otkrij' })).toHaveFocus()
    })
    it('leaves focus alone when it was not inside the navigation', () => {
      const flip = mockMedia(false)
      renderUi(<TopBar {...props()} />)
      act(() => screen.getByRole('button', { name: 'Nalog' }).focus())
      flip(true)
      expect(screen.getByRole('button', { name: 'Nalog' })).toHaveFocus()
    })
  })
  describe('narrow window', () => {
    it('shows one Menu button with the five pages', () => {
      window.matchMedia = vi.fn((query) => ({ matches: true, media: query, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
      const p = props({ page: 'discover' })
      renderUi(<TopBar {...p} />)
      expect(window.matchMedia).toHaveBeenCalledWith('(max-width: 999.98px)')
      for (const name of PAGES) expect(screen.queryByRole('button', { name })).toBeNull()
      const menuBtn = screen.getByRole('button', { name: 'Meni' })
      expect(menuBtn).toHaveAttribute('aria-haspopup', 'menu')
      fireEvent.click(menuBtn)
      const items = within(screen.getByRole('menu')).getAllByRole('menuitem')
      expect(items.map((i) => i.textContent)).toEqual(PAGES)
      expect(screen.getByRole('menuitem', { name: 'Otkrij' })).toHaveAttribute('aria-current', 'page')
      fireEvent.click(screen.getByRole('menuitem', { name: 'Watchlist' }))
      expect(p.onNavigate).toHaveBeenCalledWith('watchlist', { focusMain: true })
      expect(screen.queryByRole('menu')).toBeNull()
    })
  })
})
